/** 画好的图标 → <svg class="lt-glyph">（跟着方块的字色；不带名字：名字在调用的地方，图标本身给眼睛看） @param {string} key */
export function glyph(key) {
  const kids = GLYPHS[key] || GLYPHS.bag;
  return h('svg.lt-glyph.g-' + (GLYPHS[key] ? key : 'bag'), { viewBox: '0 0 24 24', 'aria-hidden': 'true', focusable: 'false' },
    kids.map(([tag, attrs]) => h(tag, { svg: true, ...Object.fromEntries(Object.entries(attrs).filter(([, v]) => v != null)) })));
}

/**
 * 一张清单（或者面板里还没存的 { kind, icon, color }）的图标方块：<span class="list-tile tint-绿 …">。
 * cls 是各处的大小（.list-icon 首页 36、.lp-icon 清单页 46、.sr-list-ic 搜索 28、.list-chip-ic 小标签、.shop-icon 购物模式、.le-preview 面板）；
 * 方块给眼睛看（aria-hidden），读屏念旁边的清单名
 */
export function listTile(list, cls = '') {
  const look = listLook(list);
  const kids = look.glyph ? glyph(look.glyph)
    : h('span.lt-text' + (look.emoji ? '.lt-emoji' : look.two ? '.lt-two' : ''), null, look.text);
  return h('span.list-tile.tint-' + look.color + (cls ? '.' + cls.split(' ').join('.') : ''), { 'aria-hidden': 'true' }, kids);
}
